def test_post_generate_session_id_unique_per_request():
    """Two successive requests must produce different session_ids.

    Each request uses its own TestClient instance so that sse-starlette's
    AppStatus.should_exit_event is reset to a fresh asyncio.Event for each
    request's event loop — avoiding the "bound to a different event loop" error
    that occurs when two SSE calls share a single TestClient.
    """
    from sse_starlette.sse import AppStatus

    session_ids = []
    for _ in range(2):
        AppStatus.should_exit_event = None
        with patch(
            "app.main._run_workflow",
            side_effect=_make_workflow_side_effect(),
        ):
            with TestClient(app, raise_server_exceptions=True) as single_client:
                response = single_client.post("/generate", json=VALID_BODY)
        events = _parse_sse_data_lines(response.text)
        assert events, "Expected SSE events from request"
        session_ids.append(events[0]["session_id"])

    assert session_ids[0] != session_ids[1], (
        f"Both requests produced the same session_id: {session_ids[0]!r}"
    )


