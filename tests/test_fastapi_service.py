def _make_workflow_side_effect(template_events=None):
    """Return a side_effect function that injects the real session_id into events.

    Using side_effect (rather than return_value) lets tests assert on the
    actual UUID generated by the endpoint, because the mock receives it as
    its first argument and propagates it into every event.
    """
    events = template_events or _TEMPLATE_EVENTS

    def _side_effect(session_id, travel_request):
        return [{**ev, "session_id": session_id} for ev in events]

    return _side_effect


