def _parse_sse_data_lines(body: str) -> list[dict]:
    """Extract and parse every ``data: ...`` line from a raw SSE response body.

    Args:
        body: Raw response text from an SSE endpoint.

    Returns:
        Parsed event dicts in the order they appear in the stream.
    """
    events = []
    for line in body.splitlines():
        line = line.strip()
        if line.startswith("data: "):
            payload = line[len("data: "):]
            try:
                events.append(json.loads(payload))
            except json.JSONDecodeError:
                pass
    return events


