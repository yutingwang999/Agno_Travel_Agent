"""FastAPI application entry point.

Exposes:
    GET  /health                  — liveness probe
    POST /generate                — execute the travel itinerary workflow and stream each
                                    step's result as Server-Sent Events (text/event-stream)
                                    as soon as the step finishes
    GET  /traces/{session_id}     — return all trace_events rows for a session as JSON
    GET  /                        — serve the static frontend (index.html)
"""

import json
import os
import uuid
from typing import Iterator, Optional

from agno.run.workflow import StepCompletedEvent
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException, Query, Request
from fastapi.responses import JSONResponse
from fastapi.staticfiles import StaticFiles
from sqlalchemy import create_engine, select
from sqlalchemy.orm import Session
from sse_starlette.sse import EventSourceResponse
from starlette.concurrency import iterate_in_threadpool

from app.models.trace_event import TraceEvent
from app.workflow.input_guard import GuardRejection, guard_request
from app.workflow.intake_model import TravelRequest
from app.workflow.travel_workflow import travel_workflow

load_dotenv()

app = FastAPI(
    title="Travel Itinerary Planner",
    description="AI-powered travel itinerary planning using CAG + RAG workflow",
    version="0.2.0",
)


@app.exception_handler(GuardRejection)
async def guard_rejection_handler(request: Request, exc: GuardRejection) -> JSONResponse:
    """Return a guard refusal as 422 ``{"reason": <code>, "detail": <fixed message>}``.

    Field validation errors keep FastAPI's default body (``{"detail": [...]}``),
    so the presence of ``reason`` tells the two apart.
    """
    return JSONResponse(status_code=422, content={"reason": exc.reason, "detail": exc.detail})


@app.get("/health")
async def health_check():
    return {"status": "ok"}


def _parse_sse_event(content) -> Optional[dict]:
    """Return the SSE event dict a step serialised into its content, or ``None``.

    Agno uses plain-text placeholder strings for some step outputs; anything
    that is not a JSON object with a ``step`` key is not an SSE event.
    """
    try:
        event = json.loads(content)
    except (json.JSONDecodeError, TypeError):
        return None
    return event if isinstance(event, dict) and "step" in event else None


def build_additional_data(
    session_id: str,
    travel_request: TravelRequest,
    template_version: Optional[int] = None,
) -> dict:
    """Return the ``additional_data`` every workflow step reads its request fields from.

    The evaluation harness builds retrieval queries from the same dict, so it
    measures the query the workflow actually sends.
    """
    return {
        "session_id": session_id,
        "destination": travel_request.destination,
        "trip_length": travel_request.trip_length,
        "budget": travel_request.budget,
        "travel_style": travel_request.travel_style,
        "max_daily_budget_aud": travel_request.max_daily_budget_aud,
        "notes": travel_request.notes,
        "template_version": template_version,
    }


def _run_workflow(
    session_id: str,
    travel_request: TravelRequest,
    template_version: Optional[int] = None,
) -> Iterator[dict]:
    """Run the Agno workflow and yield each step's SSE event as the step finishes.

    Uses Agno's streaming run: every step yields a ``StepCompletedEvent``
    carrying its ``StepOutput`` content.  Events come out in execution order:
    intake → cag_match → retrieval_decision → rag_retrieve → generate
    → validate_output.

    This is a blocking generator — each ``next()`` runs the workflow up to the
    next finished step — so callers on the event loop must iterate it in a
    worker thread.  Nothing runs until the first ``next()``, and the workflow
    stops at the next step boundary if the caller stops iterating.

    Args:
        session_id:        Unique identifier for this request, generated by the
                           caller and propagated through ``additional_data``.
        travel_request:    Validated and normalised ``TravelRequest`` instance.
        template_version:  Optional specific prompt template version to use.
                           When ``None`` the active version is used (default).

    Yields:
        One SSE event dict per executed step.
    """
    run_events = travel_workflow.run(
        input=(
            f"plan a {travel_request.trip_length}-day trip "
            f"to {travel_request.destination}"
        ),
        additional_data=build_additional_data(session_id, travel_request, template_version),
        stream=True,
        stream_events=True,
    )
    for run_event in run_events:
        if isinstance(run_event, StepCompletedEvent):
            event = _parse_sse_event(run_event.content)
            if event is not None:
                yield event


@app.get("/traces/{session_id}")
def get_traces(session_id: str):
    """Return all trace_events rows for the given session_id as a JSON array.

    Rows are ordered by ``created_at`` ascending.  Returns 404 when no rows
    exist for the session_id.

    Args:
        session_id: The session identifier used when the workflow was executed.

    Returns:
        A JSON array of trace event objects.  Each object contains at minimum:
        ``session_id``, ``step_name``, ``status``, ``latency_ms``, ``created_at``.
        The ``generate`` step row also includes ``prompt_template_key`` and
        ``prompt_template_version``.

    Raises:
        HTTPException 404: when no trace rows exist for the session_id.
    """
    db_url = os.environ.get("DATABASE_URL")
    if not db_url:
        raise HTTPException(status_code=500, detail="DATABASE_URL not configured")

    engine = create_engine(db_url)
    with Session(engine) as db_session:
        rows = db_session.execute(
            select(TraceEvent)
            .where(TraceEvent.session_id == session_id)
            .order_by(TraceEvent.created_at)
        ).scalars().all()

    if not rows:
        raise HTTPException(
            status_code=404,
            detail=f"No trace events found for session_id={session_id!r}",
        )

    return [
        {
            "session_id": row.session_id,
            "step_name": row.step_name,
            "status": row.status,
            "latency_ms": row.latency_ms,
            "prompt_template_key": row.prompt_template_key,
            "prompt_template_version": row.prompt_template_version,
            "degraded_mode": row.degraded_mode,
            "error_type": row.error_type,
            "created_at": row.created_at.isoformat() if row.created_at else None,
        }
        for row in rows
    ]


@app.post("/generate")
async def generate(
    request: TravelRequest,
    template_version: Optional[int] = Query(
        default=None,
        description=(
            "Optional prompt template version override. "
            "When omitted the active version is used. "
            "Use this to reproduce a past run or test a specific version."
        ),
    ),
):
    """Execute the travel itinerary workflow and stream results as SSE.

    FastAPI automatically returns 422 Unprocessable Entity when ``request``
    fails Pydantic validation (missing or invalid fields).  The input guards
    then run before the workflow: a prompt-injection match or a destination that
    is not an Australian place is refused with 422 and a reason code (see
    :mod:`app.workflow.input_guard`); an accepted destination is replaced by its
    canonical English name.

    Each yielded ``data`` event is a JSON-serialised SSE event matching the
    structure defined in DESIGN.md section 9:
        {
            "session_id": "...",
            "step": "intake",
            "status": "completed",
            "timestamp": "...",
            "data": {},
            "error": null
        }

    Args:
        request:          Validated travel planning request body.
        template_version: Optional prompt template version override (query param).

    Returns:
        A ``text/event-stream`` response that emits one SSE event per workflow
        step.  The first event always contains the ``session_id``.
    """
    request = guard_request(request)
    session_id = str(uuid.uuid4())

    async def event_generator():
        # Each step runs in a worker thread so the event loop stays free; an
        # event is sent as soon as its step finishes.  If the client
        # disconnects, iteration stops and no further step is started.
        events = _run_workflow(session_id, request, template_version)
        async for event in iterate_in_threadpool(events):
            yield {"data": json.dumps(event)}

    return EventSourceResponse(event_generator())


