"""FastAPI application entry point.

Exposes:
    GET  /health    — liveness probe
    POST /generate  — execute the travel itinerary workflow and stream results
                      as Server-Sent Events (text/event-stream)
"""

import contextlib
import io
import json
import uuid

from dotenv import load_dotenv
from fastapi import FastAPI
from sse_starlette.sse import EventSourceResponse

from app.workflow.intake_model import TravelRequest
from app.workflow.travel_workflow import travel_workflow

load_dotenv()

app = FastAPI(
    title="Travel Itinerary Planner",
    description="AI-powered travel itinerary planning using CAG + RAG workflow",
    version="0.1.0",
)


@app.get("/health")
async def health_check():
    return {"status": "ok"}


# Canonical step order for sorting collected SSE events before streaming.
_STEP_ORDER: dict[str, int] = {
    "intake": 0,
    "cag_match": 1,
    "retrieval_decision": 2,
    "rag_retrieve": 3,
    "generate": 4,
    "validate_output": 5,
}


def _collect_step_result_events(step_results) -> list[dict]:
    """Walk step_results (including nested Condition sub-steps) and return SSE events.

    Agno inserts plain-text placeholder strings for skipped Condition branches;
    those are silently ignored.

    Args:
        step_results: The ``step_results`` list from a ``WorkflowRunResponse``.

    Returns:
        A list of SSE event dicts in the order they appear in ``step_results``.
    """
    events: list[dict] = []
    for step_result in step_results:
        if step_result.steps:
            # Condition node — recurse into sub-steps (e.g. rag_retrieve)
            for sub in step_result.steps:
                if sub.content:
                    try:
                        events.append(json.loads(sub.content))
                    except (json.JSONDecodeError, TypeError):
                        pass  # Agno placeholder string for a skipped branch
        elif step_result.content:
            try:
                events.append(json.loads(step_result.content))
            except (json.JSONDecodeError, TypeError):
                pass
    return events


def _run_workflow(session_id: str, travel_request: TravelRequest) -> list[dict]:
    """Execute the Agno workflow synchronously and collect all SSE events.

    The ``retrieval_decision`` evaluator emits its SSE event by printing to
    stdout (a side-effect established in ``feat/workflow-skeleton``).  This
    function captures that output so the event can be included in the SSE
    stream.

    Args:
        session_id:      Unique identifier for this request, generated by the
                         caller and propagated through ``additional_data``.
        travel_request:  Validated and normalised ``TravelRequest`` instance.

    Returns:
        A list of SSE event dicts sorted in workflow execution order:
        intake → cag_match → retrieval_decision → (rag_retrieve) → generate
        → validate_output.
    """
    additional_data = {
        "session_id": session_id,
        "destination": travel_request.destination,
        "trip_length": travel_request.trip_length,
        "budget": travel_request.budget,
        "travel_style": travel_request.travel_style,
    }

    # Capture stdout so the retrieval_decision evaluator's print() is collected
    # rather than sent to the server's stdout.
    captured_stdout = io.StringIO()
    with contextlib.redirect_stdout(captured_stdout):
        result = travel_workflow.run(
            input=(
                f"plan a {travel_request.trip_length}-day trip "
                f"to {travel_request.destination}"
            ),
            additional_data=additional_data,
        )

    # Collect events from all step executors (all steps except retrieval_decision)
    all_events = _collect_step_result_events(result.step_results)

    # Parse the retrieval_decision event emitted to stdout
    stdout_text = captured_stdout.getvalue().strip()
    if stdout_text:
        # stdout may contain multiple lines if Agno logs anything there;
        # iterate and collect any valid JSON SSE events.
        for line in stdout_text.splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                event = json.loads(line)
                if isinstance(event, dict) and "step" in event:
                    all_events.append(event)
            except (json.JSONDecodeError, TypeError):
                pass

    # Sort events into canonical workflow order before streaming
    all_events.sort(key=lambda e: _STEP_ORDER.get(e.get("step", ""), 99))

    return all_events


@app.post("/generate")
async def generate(request: TravelRequest):
    """Execute the travel itinerary workflow and stream results as SSE.

    FastAPI automatically returns 422 Unprocessable Entity when ``request``
    fails Pydantic validation (missing or invalid fields).

    Each yielded ``data`` event is a JSON-serialised SSE event matching the
    structure defined in DESIGN.md section 9:
        {
            "session_id": "...",
            "step": "intake",
            "status": "completed",
            "timestamp": "...",
            "data": {},
            "error": null
        }

    Args:
        request: Validated travel planning request body.

    Returns:
        A ``text/event-stream`` response that emits one SSE event per workflow
        step.  The first event always contains the ``session_id``.
    """
    session_id = str(uuid.uuid4())

    async def event_generator():
        # Run the synchronous workflow (blocking call kept simple for prototype)
        events = _run_workflow(session_id, request)
        for event in events:
            yield {"data": json.dumps(event)}

    return EventSourceResponse(event_generator())
